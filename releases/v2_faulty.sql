    GITHUB_LAB.DEV.VW_CUSTOMER_RELEASE
    COPY GRANTS AS
SELECT
    CUSTOMER_ID,
    CUSTOMER_NAME,
    CITY,
    EMAIL,
    COALESCE(CUSTOMER_STATUS, 'UNKNOWN')

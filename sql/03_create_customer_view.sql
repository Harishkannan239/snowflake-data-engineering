
-- Feature: Customer reporting view
-- Version: 3
-- Environment: DEV

CREATE SCHEMA IF NOT EXISTS GITHUB_LAB.DEV;

CREATE OR REPLACE VIEW GITHUB_LAB.DEV.VW_CUSTOMER_CONTACTS AS
SELECT
    CUSTOMER_ID,
    CUSTOMER_NAME,
    CITY,
    EMAIL,
    COALESCE(CUSTOMER_STATUS, 'UNKNOWN') AS CUSTOMER_STATUS,
    CREATED_AT
FROM GITHUB_LAB.BRONZE.CUSTOMERS;


-- Automated CI/CD deployment
-- Target environment: DEV

CREATE VIEW IF NOT EXISTS
    GITHUB_LAB.DEV.VW_CUSTOMER_CICD AS
SELECT
    CUSTOMER_ID,
    CUSTOMER_NAME,
    CITY,
    EMAIL,
    COALESCE(
        CUSTOMER_STATUS,
        'UNKNOWN'
    ) AS CUSTOMER_STATUS
FROM GITHUB_LAB.BRONZE.CUSTOMERS;
